// Renders composition frames. Usage: node render.cjs out_dir [frames...]  (no frames = all)
const fs = require('fs')
const path = require('path')
const { chromium } = require('playwright')
;(async () => {
  const [out = 'frames', ...list] = process.argv.slice(2)
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 })
  page.setDefaultTimeout(60000)
  page.on('pageerror', (e) => console.log('pageerror', e.message))
  page.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()) })
  await page.goto('http://localhost:5173/brag-output/work/comp/index.html')
  await page.waitForFunction(() => window.renderFrame && window.compReady)
  await page.evaluate(() => window.compReady)
  const total = await page.evaluate(() => window.TOTAL)
  const frames = list.length ? list.map(Number) : Array.from({ length: total }, (_, i) => i)
  const t0 = Date.now()
  for (const f of frames) {
    await page.evaluate((f) => window.renderFrame(f), f)
    await page.screenshot({ path: path.join(out, String(f).padStart(4, '0') + '.jpg'), type: 'jpeg', quality: 95 })
    if (f % 60 === 0) console.log('frame', f, ((Date.now() - t0) / 1000).toFixed(0) + 's')
  }
  console.log('rendered', frames.length)
  await browser.close()
})().catch((e) => { console.error('FAILED', e); process.exit(1) })
